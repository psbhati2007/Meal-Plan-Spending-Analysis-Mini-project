def search_meals(category=None, meal=None):
    try:
        df = pd.read_csv(FILE_NAME)

        if df.empty:
            print("No records available.")
            return

        result = df.copy()

        if category:
            result = result[
                result["Category"].str.contains(
                    category,
                    case=False,
                    na=False
                )
            ]

        if meal:
            result = result[
                result["Meal"].str.contains(
                    meal,
                    case=False,
                    na=False
                )
            ]

        if result.empty:
            print("No matching records found.")
        else:
            display(result)

    except Exception as e:
        print("Error:", e)

