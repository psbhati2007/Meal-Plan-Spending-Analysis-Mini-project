"""Updating a Meal Record
This function allows an existing meal record to be updated using its Meal ID while keeping the stored data consistent.
"""

def update_meal(meal_id, date=None, meal=None,
                category=None, food_item=None, cost=None):

    try:
        df = pd.read_csv(FILE_NAME)

        if meal_id not in df["Meal_ID"].values:
            print("Meal ID not found.")
            return

        index = df.index[df["Meal_ID"] == meal_id][0]

        if date is not None:
            df.at[index, "Date"] = date

        if meal is not None:
            df.at[index, "Meal"] = meal

        if category is not None:
            df.at[index, "Category"] = category

        if food_item is not None:
            df.at[index, "Food_Item"] = food_item

        if cost is not None:
            cost = float(cost)

            if cost < 0:
                raise ValueError("Cost cannot be negative.")

            df.at[index, "Cost"] = cost

        df.to_csv(FILE_NAME, index=False)

        print("Meal updated successfully!")

    except ValueError as e:
        print("Invalid input:", e)

    except Exception as e:
        print("Error:", e)

update_meal(
    1,
    cost=100
)

