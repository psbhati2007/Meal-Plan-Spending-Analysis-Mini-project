    # --------------------------------------------------------
    # Category Analysis
    # --------------------------------------------------------

    def category_analysis():

        try:

            df = load_gui_data()

            if df.empty:

                messagebox.showinfo(
                    "Category Analysis",
                    "No data available."
                )

                return

            df["Cost"] = pd.to_numeric(
                df["Cost"],
                errors="coerce"
            )

            result_df = (
                df.groupby(
                    "Category"
                )["Cost"]
                .agg(
                    [
                        "sum",
                        "mean",
                        "count"
                    ]
                )
            )

            text = (
                "===== CATEGORY ANALYSIS =====\n\n"
            )

            for category, row in result_df.iterrows():

                text += (
                    f"Category: {category}\n"
                    f"Total Spending : ₹{row['sum']:.2f}\n"
                    f"Average Cost   : ₹{row['mean']:.2f}\n"
                    f"Number of Meals: {int(row['count'])}\n"
                    + "-" * 40
                    + "\n"
                )

            show_result(
                "Category Analysis",
                text
            )

        except Exception as e:

            messagebox.showerror(
                "Error",
                f"Unable to perform analysis:\n{e}"
            )


