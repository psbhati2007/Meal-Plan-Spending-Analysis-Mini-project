    # Search Meals
    # --------------------------------------------------------

    def search_meals():

        try:

            search_text = (
                search_var
                .get()
                .strip()
                .lower()
            )

            df = load_gui_data()

            if not search_text:

                refresh_table(
                    df
                )

                return

            if df.empty:

                refresh_table(
                    df
                )

                return

            result = df[
                df.astype(str)
                .apply(
                    lambda row:
                    row.str.lower()
                    .str.contains(
                        search_text,
                        na=False
                    )
                    .any(),
                    axis=1
                )
            ]

            refresh_table(
                result
            )

            if result.empty:

                messagebox.showinfo(
                    "Search",
                    "No matching records found."
                )

        except Exception as e:

            messagebox.showerror(
                "Error",
                f"Search failed:\n{e}"
            )


