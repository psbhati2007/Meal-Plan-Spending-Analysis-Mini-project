"""Category-wise Analysis
This section uses Pandas to calculate total spending, average cost, and number of meals for each meal category.
"""

def category_analysis():
    try:
        df = pd.read_csv(FILE_NAME)

        if df.empty:
            print("No data available.")
            return

        category_summary = df.groupby("Category")["Cost"].agg(
            ["sum", "mean", "count"]
        )

        category_summary.columns = [
            "Total_Spending",
            "Average_Cost",
            "Number_of_Meals"
        ]

        category_summary = category_summary.sort_values(
            "Total_Spending",
            ascending=False
        )

        print("===== CATEGORY ANALYSIS =====")
        display(category_summary)

    except Exception as e:
        print("Error:", e)

category_analysis()

"""Monthly Spending Analysis
This function groups meal records by month and calculates the total spending for each month.
"""

def monthly_analysis():
    try:
        df = pd.read_csv(FILE_NAME)

        if df.empty:
            print("No data available.")
            return

        df["Date"] = pd.to_datetime(df["Date"])

        df["Month"] = df["Date"].dt.to_period("M").astype(str)

        monthly = df.groupby("Month")["Cost"].sum()

        print("===== MONTHLY SPENDING =====")
        display(monthly)

        return monthly

    except Exception as e:
        print("Error:", e)

monthly_analysis()

