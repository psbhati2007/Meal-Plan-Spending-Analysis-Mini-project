def prepare_gui_file():

    try:

        if not os.path.exists(GUI_FILE):

            empty_df = pd.DataFrame(
                columns=COLUMNS
            )

            empty_df.to_csv(
                GUI_FILE,
                index=False
            )

        return True

    except Exception as e:

        print("File Error:", e)
        return False


