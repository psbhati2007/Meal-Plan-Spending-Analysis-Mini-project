"""Spending Summary
This function calculates the total, average, highest, and lowest meal spending to provide a quick overview of expenses.
"""

def spending_summary():
    try:
        df = pd.read_csv(FILE_NAME)

        if df.empty:
            print("No data available.")
            return

        total_spending = df["Cost"].sum()
        average_cost = df["Cost"].mean()
        highest_cost = df["Cost"].max()
        lowest_cost = df["Cost"].min()

        print("===== SPENDING SUMMARY =====")
        print(f"Total Spending   : ₹{total_spending:.2f}")
        print(f"Average Meal Cost: ₹{average_cost:.2f}")
        print(f"Highest Cost     : ₹{highest_cost:.2f}")
        print(f"Lowest Cost      : ₹{lowest_cost:.2f}")

    except Exception as e:
        print("Error:", e)

